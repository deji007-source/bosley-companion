import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
const context = { window: {}, Date, Math };
vm.runInNewContext(readFileSync(new URL("../src/trading/paper-account.js", import.meta.url), "utf8"), context);
vm.runInNewContext(readFileSync(new URL("../src/trading/market-intelligence.js", import.meta.url), "utf8"), context);
const accounts = context.window.BosleyPaperAccounts;
const account = accounts.createAccount({ label: "Learning account", startingBalance: 1000 });
assert.equal(account.mode, "paper");
assert.equal(accounts.summary(account).equity, 1000);
const updated = accounts.record(account, { type: "simulation", amount: -25, note: "Example simulated cost" });
assert.equal(updated.cash, 975);
assert.equal(accounts.summary(updated).pnl, -25);
const referenced = accounts.record(updated, { type: "backtest-result", amount: 40, reference: "run-unique-1" });
assert.equal(referenced.cash, 1015);
assert.equal(accounts.record(referenced, { type: "backtest-result", amount: 40, reference: "run-unique-1" }), referenced, "A retried backtest must not be applied twice");
assert.throws(() => accounts.record(updated, { amount: -2000 }), /negative cash/);
assert.throws(() => accounts.createAccount({ startingBalance: 0 }), /Starting balance/);
const bars = Array.from({ length: 40 }, (_, i) => ({ close: 100 + i * 0.5 }));
const analysis = context.window.BosleyMarketIntelligence.analyze(bars);
assert.equal(analysis.observations, 40);
assert.ok(Number.isFinite(analysis.rsi14));
assert.ok(analysis.trend.length > 0);
assert.match(analysis.disclaimer, /not a forecast/);
assert.throws(() => context.window.BosleyMarketIntelligence.analyze(bars.slice(0, 10)), /At least 20/);
const flat = context.window.BosleyMarketIntelligence.analyze(Array.from({ length: 20 }, () => ({ close: 50 })));
assert.equal(flat.rsi14, 50, "Flat price series should produce neutral RSI.");
const falling = context.window.BosleyMarketIntelligence.analyze(Array.from({ length: 20 }, (_, i) => ({ close: 100 - i })));
assert.equal(falling.rsi14, 0, "A strictly falling series should produce zero RSI.");
console.log("Paper account and market intelligence checks passed.");
